"""Model card text (P6.T5): every number is read from the run outputs, none typed by hand."""

from __future__ import annotations

import pandas as pd

from foodlens.config import Config


def _row(table: pd.DataFrame, model: str, target: str, scheme: str) -> str:
    r = table[(table["model"] == model) & (table["target"] == target) & (table["scheme"] == scheme)]
    if r.empty:
        return "n/a"
    r = r.iloc[0]
    p = "" if pd.isna(r.get("p_value")) else f", perm. p = {r['p_value']:.3f}"
    return f"{r['value']:.3f} [{r['ci_lo']:.3f}, {r['ci_hi']:.3f}] ({int(r['n_groups'])} groups{p})"


def _metrics_table(table: pd.DataFrame, model: str, cfg: Config) -> list[str]:
    ev = cfg.evaluation
    lines = ["| Model | Target | Scheme | Metric [95 % CI] |", "|---|---|---|---|"]
    for m in (model, "baseline_red_median", "baseline_mean"):
        for target in (ev.class_target, ev.targets[0]):
            for scheme in ev.group_cols:
                lines.append(f"| {m} | {target} | LOGO_{scheme} | "
                             f"{_row(table, m, target, f'LOGO_{scheme}')} |")  # fmt: skip
    return lines


def model_card(dec: dict, table: pd.DataFrame, imp: dict, bundle: dict, cfg: Config) -> str:
    """Markdown model card of the saved final bundle."""
    perm = dec.get("permutation") or {}
    chance = 1 / len(cfg.labels.classes)
    p_txt = f"{perm['p_value']:.3f} ({perm['n_permutations']} reps)" if perm else "not run"
    lines = [
        f"# Model card: {cfg.train.final_model_name}", "",
        "Generated by `foodlens finalize`; numbers come from `reports/tables/` and "
        "`reports/metrics/`.", "",
        "## Model",
        f"- Family: `{dec['family']}` (sklearn Pipeline: median impute, drop constant, scale, "
        f"top-k select, model); feature set `{dec['feature_set']}` ({len(bundle['features'])} "
        "single-shot features of one R/G/B triplet).",
        f"- Classifier: freshness level ({', '.join(bundle['classes'])}), probability-calibrated "
        f"({cfg.train.calibration_method}, inner grouped CV) if that lowers the grouped ECE. "
        "Params: "
        f"`{dec['final_params']['classifier']}`.",
        f"- Regressor: `{bundle['regression_target']}` (hours at 25 °C equivalent). Params: "
        f"`{dec['final_params']['regressor']}`.",
        f"- OOD detector: Mahalanobis (Ledoit-Wolf), threshold = {cfg.train.ood_percentile:g}th "
        "percentile of leave-one-piece-out distances within the training pieces.",
        f"- Trained on {bundle['n_train']} triplets from {bundle['n_groups']} pieces; config "
        f"`{bundle['config_hash']}`, commit `{bundle['git_commit']}`.", "",
        "## Selection (rule fixed before results, `train.selection`)",
        f"- Selected `{dec['model']}`: {dec['metric']} = {dec['value']:.3f} "
        f"[{dec['ci'][0]:.3f}, {dec['ci'][1]:.3f}]; best single-shot baseline "
        f"`{dec['best_baseline']}` = {dec['best_baseline_value']:.3f}; chance = {chance:.2f}.",
        f"- Meets the rule (CI lower bound > best baseline): **{dec['meets_rule']}**. "
        f"Ties within {cfg.train.selection.tie_tol}: {dec['tied_with'] or 'none'}.",
        f"- Grouped permutation test (labels shuffled within each piece): p = {p_txt}.", "",
        "## Grouped CV metrics (out-of-fold, never tuned on the test piece)",
        *_metrics_table(table, dec["model"], cfg), "",
        *_results(dec, imp), *_limits(bundle),
    ]  # fmt: skip
    return "\n".join(lines)


def _results(dec: dict, imp: dict) -> list[str]:
    cal = dec["calibration"]
    ood = cal["ood"]
    top = imp["classification"].query("kind == 'feature'")["item"].head(5).tolist()
    fams = imp["classification"].query("kind == 'family'").head(4)
    fam_txt = ", ".join(f"{r.item} ({r.mean:+.3f})" for r in fams.itertuples())
    return [
        "## Calibration and abstention (leave-one-piece-out)",
        f"- ECE {cal['metrics']['uncalibrated']['ece']:.3f} -> "
        f"{cal['metrics']['calibrated']['ece']:.3f}; Brier "
        f"{cal['metrics']['uncalibrated']['brier']:.3f} -> "
        f"{cal['metrics']['calibrated']['brier']:.3f}. Final model uses the "
        f"{'calibrated' if cal['use_calibrated'] else 'uncalibrated'} classifier (lower ECE).",
        *[f"- OOD ({o['threshold_mode']} threshold): abstains on {o['abstention_rate']:.1%} of "
          f"held-out triplets; accuracy kept {o['accuracy_kept']:.3f} vs all "
          f"{o['accuracy_all']:.3f}, balanced accuracy kept {o['balanced_accuracy_kept']:.3f} vs "
          f"all {o['balanced_accuracy_all']:.3f} (always read together)." for o in ood],
        f"- OOD sanity check: held-out triplets with RED/BLUE features swapped (simulated wrong "
        f"LED) are flagged in {ood[0]['shift_check_flag_rate_RB_swapped']:.1%} of cases.",
        "",
        "## What the model looks at (held-out permutation importance)",
        f"- Top features: {', '.join(f'`{t}`' for t in top)}.",
        f"- Top families: {fam_txt}.", "",
    ]  # fmt: skip


def _limits(bundle: dict) -> list[str]:
    return [
        "## Intended use and limits",
        "- Research prototype: indicative freshness level of raw chicken photographed in THE SAME "
        "dark box, LEDs, camera and settings as the training data. Not a food-safety device.",
        "- Labels are temperature-equivalent hours since filming started, not microbial counts; "
        "glints are specular reflections (moisture), not bacteria.",
        f"- Only {bundle['n_groups']} pieces; the `spoiled_risk` level comes from 2 overnight "
        "pieces only. CIs are wide; new pieces/setups may fall outside the training range "
        "(the OOD check abstains then).",
        "- Unknown storage history before filming is not modelled (open questions 2, 10).", "",
    ]  # fmt: skip
